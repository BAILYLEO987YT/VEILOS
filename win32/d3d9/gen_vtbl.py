# Make src/vtbl.rs, d3d9.dll's COM vtables, from interfaces.txt and the
# methods implemented in src/: a method M of interface I is the function
# `<short>_M` (short names below) of I or, failing that, of the nearest base
# that has one, or of IDirect3DResource9 (GetDevice, private data);
# otherwise a stub that notes the call once and fails it (or returns 0).
# Run after adding or renaming a method: python gen_vtbl.py
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SHORT = {
    'IUnknown': 'Unk', 'IDirect3D9': 'D3D', 'IDirect3DDevice9': 'Dev', 'IDirect3DStateBlock9': 'SB',
    'IDirect3DSwapChain9': 'SC', 'IDirect3DResource9': 'Res', 'IDirect3DVertexDeclaration9': 'Decl',
    'IDirect3DVertexShader9': 'VS', 'IDirect3DPixelShader9': 'PS', 'IDirect3DBaseTexture9': 'Base',
    'IDirect3DTexture9': 'Tex', 'IDirect3DVolumeTexture9': 'VolTex', 'IDirect3DCubeTexture9': 'Cube',
    'IDirect3DVertexBuffer9': 'VB', 'IDirect3DIndexBuffer9': 'IB', 'IDirect3DSurface9': 'Surf',
    'IDirect3DVolume9': 'Vol', 'IDirect3DQuery9': 'Query',
}

ifaces, order = {}, []
for line in open(os.path.join(HERE, 'interfaces.txt')):
    if line.startswith('#') or not line.strip():
        continue
    if not line.startswith(' '):
        name, base = [x.strip() for x in line.split(':')]
        ifaces[name] = (base, [])
        order.append(name)
    else:
        m, ret = line.split()
        ifaces[name][1].append((m, ret))

impls = {}
for f in sorted(os.listdir(os.path.join(HERE, 'src'))):
    if not f.endswith('.rs') or f == 'vtbl.rs':
        continue
    mod = f[:-3]
    text = open(os.path.join(HERE, 'src', f), encoding='utf-8').read()
    # Functions, and pairs a macro makes (`consts!(Dev_SetX, Dev_GetX, ...)`).
    names = re.findall(r'fn ((\w+?)_(\w+))\s*\(', text)
    for m in re.finditer(r'\w+!\((\w+), (\w+),', text):
        names += [(n, n.split('_', 1)[0], n.split('_', 1)[1]) for n in m.groups() if '_' in n]
    for m in names:
        if m[1] in SHORT.values():
            impls[m[0]] = f'crate::{mod}::{m[0]}' if mod != 'lib' else f'crate::{m[0]}'

def chain(i):
    out = [i]
    while i in ifaces:
        i = ifaces[i][0]
        out.append(i)
    return out

out = ['// Generated by gen_vtbl.py from interfaces.txt: do not edit.', '',
       '#![allow(non_snake_case, dead_code)]', '', 'use crate::com::{unimplemented, Vtbl, D3DERR_INVALIDCALL};', '']
stubs = []
for i in order:
    base, methods = ifaces[i]
    out.append(f'pub static {i.upper()}: Vtbl<{len(methods)}> = Vtbl([')
    for m, ret in methods:
        # The resource methods (GetDevice, private data) serve every object.
        f = next((impls[f'{SHORT[c]}_{m}'] for c in chain(i) + ['IDirect3DResource9'] if f'{SHORT[c]}_{m}' in impls), None)
        if f is None:
            f = f'stub_{SHORT[i]}_{m}'
            note = f'unimplemented(b"{i}::{m}\\0")'
            if ret == 'HRESULT':
                stubs.append(f'unsafe extern "system" fn {f}() -> i32 {{\n    {note};\n    D3DERR_INVALIDCALL\n}}')
            elif ret == 'float':
                stubs.append(f'unsafe extern "system" fn {f}() -> f32 {{\n    {note};\n    0.0\n}}')
            else:
                stubs.append(f'unsafe extern "system" fn {f}() -> usize {{\n    {note};\n    0\n}}')
        out.append(f'    {f} as *const (),')
    out.append(']);')
    out.append('')
out += stubs
open(os.path.join(HERE, 'src', 'vtbl.rs'), 'w', newline='\n').write('\n'.join(out) + '\n')
print(f'{len(order)} interfaces, {sum(len(v[1]) for v in ifaces.values())} methods, {len(stubs)} stubs')
