# Make src/vtbl.rs, d3d11.dll's COM vtables (DXGI's too), from interfaces.txt and the
# methods implemented in src/: a method M of interface I is the function
# `<short>_M` (short names below) of I or, failing that, of the nearest base
# that has one, or of ID3D11DeviceChild (GetDevice, private data);
# otherwise a stub that notes the call once and fails it (or returns 0).
# Run after adding or renaming a method: python gen_vtbl.py
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SHORT = {
    'IUnknown': 'Unk', 'IDXGIObject': 'DxObj', 'IDXGIDeviceSubObject': 'DxSub', 'IDXGIResource': 'DxRes',
    'IDXGISurface': 'Surf', 'IDXGISurface1': 'Surf1', 'IDXGIAdapter': 'Adp', 'IDXGIAdapter1': 'Adp1',
    'IDXGIOutput': 'Out', 'IDXGISwapChain': 'SC', 'IDXGISwapChain1': 'SC1', 'IDXGIFactory': 'Fac',
    'IDXGIFactory1': 'Fac1', 'IDXGIFactory2': 'Fac2', 'IDXGIDevice': 'DxDev', 'IDXGIDevice1': 'DxDev1',
    'ID3D11DeviceChild': 'Child', 'ID3D11DepthStencilState': 'DSS', 'ID3D11BlendState': 'BS',
    'ID3D11RasterizerState': 'RS', 'ID3D11Resource': 'Res', 'ID3D11Buffer': 'Buf', 'ID3D11Texture1D': 'T1',
    'ID3D11Texture2D': 'T2', 'ID3D11Texture3D': 'T3', 'ID3D11View': 'View', 'ID3D11ShaderResourceView': 'SRV',
    'ID3D11RenderTargetView': 'RTV', 'ID3D11DepthStencilView': 'DSV', 'ID3D11UnorderedAccessView': 'UAV',
    'ID3D11VertexShader': 'VS', 'ID3D11HullShader': 'HS', 'ID3D11DomainShader': 'DS', 'ID3D11GeometryShader': 'GS',
    'ID3D11PixelShader': 'PS', 'ID3D11ComputeShader': 'CS', 'ID3D11InputLayout': 'IL', 'ID3D11SamplerState': 'Samp',
    'ID3D11Asynchronous': 'Async', 'ID3D11Query': 'Query', 'ID3D11Predicate': 'Pred', 'ID3D11Counter': 'Ctr',
    'ID3D11ClassLinkage': 'CL', 'ID3D11CommandList': 'CmdL', 'ID3D11DeviceContext': 'Ctx', 'ID3D11Device': 'Dev',
}

ifaces, order, guids = {}, [], {}
for line in open(os.path.join(HERE, 'interfaces.txt')):
    if line.startswith('#') or not line.strip():
        continue
    if not line.startswith(' '):
        name, rest = [x.strip() for x in line.split(':')]
        base, guid = rest.split()
        ifaces[name] = (base, [])
        guids[name] = guid.strip('{}')
        order.append(name)
    else:
        m, ret = line.split()
        ifaces[name][1].append((m, ret))

impls = {}
for f in sorted(os.listdir(os.path.join(HERE, 'src'))):
    if not f.endswith('.rs') or f == 'vtbl.rs':
        continue
    mod = f[:-3]
    text = open(os.path.join(HERE, 'src', f), encoding='utf-8').read()
    # Functions, and pairs a macro makes (`consts!(Dev_SetX, Dev_GetX, ...)`).
    names = re.findall(r'fn ((\w+?)_(\w+))\s*\(', text)
    for m in re.finditer(r'\w+!\(([^()]*)\)', text):
        for n in [x.strip() for x in m.group(1).split(',')]:
            if re.fullmatch(r'\w+_\w+', n):
                names.append((n, n.split('_', 1)[0], n.split('_', 1)[1]))
    for m in names:
        if m[1] in SHORT.values():
            impls[m[0]] = f'crate::{mod}::{m[0]}' if mod != 'lib' else f'crate::{m[0]}'

def chain(i):
    out = [i]
    while i in ifaces:
        i = ifaces[i][0]
        out.append(i)
    return out

out = ['// Generated by gen_vtbl.py from interfaces.txt: do not edit.', '',
       '#![allow(non_snake_case, dead_code)]', '', 'use crate::com::{unimplemented, Guid, Vtbl, E_NOTIMPL};', '']
for i in order:
    g = guids[i].split('-')
    b = bytes.fromhex(g[3] + g[4])
    out.append(f'pub const IID_{i.upper()}: Guid = Guid(0x{g[0]}, 0x{g[1]}, 0x{g[2]}, [{", ".join("0x%02x" % x for x in b)}]);')
out.append('')
stubs = []
for i in order:
    base, methods = ifaces[i]
    out.append(f'pub static {i.upper()}: Vtbl<{len(methods)}> = Vtbl([')
    for m, ret in methods:
        # The resource methods (GetDevice, private data) serve every object.
        f = next((impls[f'{SHORT[c]}_{m}'] for c in chain(i) + ['ID3D11DeviceChild'] if f'{SHORT[c]}_{m}' in impls), None)
        if f is None:
            f = f'stub_{SHORT[i]}_{m}'
            note = f'unimplemented(b"{i}::{m}\\0")'
            if ret == 'HRESULT':
                stubs.append(f'unsafe extern "system" fn {f}() -> i32 {{\n    {note};\n    E_NOTIMPL\n}}')
            elif ret in ('float', 'FLOAT'):
                stubs.append(f'unsafe extern "system" fn {f}() -> f32 {{\n    {note};\n    0.0\n}}')
            else:
                stubs.append(f'unsafe extern "system" fn {f}() -> usize {{\n    {note};\n    0\n}}')
        out.append(f'    {f} as *const (),')
    out.append(']);')
    out.append('')
out += stubs
open(os.path.join(HERE, 'src', 'vtbl.rs'), 'w', newline='\n').write('\n'.join(out) + '\n')
print(f'{len(order)} interfaces, {sum(len(v[1]) for v in ifaces.values())} methods, {len(stubs)} stubs')
